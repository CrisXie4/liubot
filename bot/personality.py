import json
import os

from . import cache

CONFIG_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data", "personality.json")

DEFAULT = {
    "name": "小Q",
    "personality": "活泼",
    "traits": ["友好", "幽默", "乐于助人"],
    "custom_prompt": "",
    "temperature": 0.8,
    "max_tokens": 800,
    "reply_style": "conversational",  # conversational / concise / detailed
    "auto_chat": False,               # 是否主动搭话
    "auto_chat_probability": 0.05,    # 主动搭话概率
    "auto_chat_cooldown": 300,        # 主动搭话冷却（秒）
}


def load() -> dict:
    """读取人设配置（带缓存，减少文件 IO）"""
    cached = cache.personality_cache.get("personality")
    if cached is not None:
        return cached

    if os.path.exists(CONFIG_PATH):
        try:
            with open(CONFIG_PATH, "r", encoding="utf-8") as f:
                cfg = json.load(f)
            result = {**DEFAULT, **cfg}
            cache.personality_cache.set("personality", result)
            return result
        except Exception:
            pass
    result = dict(DEFAULT)
    cache.personality_cache.set("personality", result)
    return result


def save(cfg: dict):
    os.makedirs(os.path.dirname(CONFIG_PATH), exist_ok=True)
    merged = {**DEFAULT, **cfg}
    # 只保存与默认值不同的项，保持文件干净
    to_save = {k: v for k, v in merged.items() if DEFAULT.get(k) != v}
    with open(CONFIG_PATH, "w", encoding="utf-8") as f:
        json.dump(to_save, f, ensure_ascii=False, indent=2)
    # 使缓存失效
    cache.personality_cache.invalidate("personality")


# 平台机制附录 — 与人设无关的"硬约定"。
