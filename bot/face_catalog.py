# prompt 里已用但含义由原 prompt 定义的补充项不再重复；如需扩展在此追加。


def render_face_menu(per_line: int = 8) -> str:
    """渲染成注入 prompt 的紧凑菜单（:id:含义），静态内容可被前缀缓存。"""
    items = [f":{fid}:{name}" for fid, name in sorted(FACE_CATALOG.items())]
    lines = [
        " ".join(items[i:i + per_line])
        for i in range(0, len(items), per_line)
    ]
    return "\n".join(lines)
